package application.domain.services.returns;

import application.domain.enums.BusinessOperation;
import application.domain.exceptions.EntityNotFoundException;
import application.domain.models.Administrator;
import application.domain.models.Person;
import application.domain.models.Refund;
import application.domain.models.Return;
import application.domain.ports.out.NotificationService;
import application.domain.ports.out.ReturnRepository;
import application.domain.services.ServiceValidations;
import application.domain.services.authorization.ValidateOwnershipAccessService;
import application.domain.services.authorization.ValidatePermissionsService;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.UUID;

/**
 * ProcessRefundService
 *
 * Catalog service "Process Refund". A Refund can only be generated
 * from an approved Return and must be approved by an Administrator.
 * By default the reimbursed amount is the total of the order,
 * and it can never exceed it.
 */
public class ProcessRefundService {

    private final ReturnRepository returnRepository;
    private final ValidatePermissionsService permissionsService;
    private final ValidateOwnershipAccessService ownershipService;
    private final NotificationService notificationService;

    public ProcessRefundService(ReturnRepository returnRepository,
                                ValidatePermissionsService permissionsService,
                                ValidateOwnershipAccessService ownershipService,
                                NotificationService notificationService) {
        if (returnRepository == null || permissionsService == null || ownershipService == null
                || notificationService == null) {
            throw new IllegalArgumentException("ProcessRefundService requires its dependencies");
        }
        this.returnRepository = returnRepository;
        this.permissionsService = permissionsService;
        this.ownershipService = ownershipService;
        this.notificationService = notificationService;
    }

    /**
     * @param approverId identifier of the Administrator approving the refund
     * @param returnId   identifier of the approved Return
     * @param amount     amount to reimburse (when null, the order total is used)
     * @return the processed Refund
     */
    public Refund processRefund(String approverId, String returnId, BigDecimal amount) {
        Person approver = permissionsService.requirePermission(approverId, BusinessOperation.PROCESS_REFUND);
        Return returnRequest = findReturn(returnId);

        BigDecimal orderTotal = returnRequest.getOrder().getTotalAmount();
        BigDecimal refundAmount = amount == null ? orderTotal : amount;
        if (refundAmount.compareTo(orderTotal) > 0) {
            throw new IllegalArgumentException("Refund amount " + refundAmount
                    + " exceeds the order total " + orderTotal);
        }

        Refund refund = Refund.issueFor(returnRequest, refundAmount, (Administrator) approver,
                UUID.randomUUID().toString(), LocalDateTime.now());
        refund.process();

        returnRepository.save(returnRequest);
        notificationService.notify(returnRequest.getBuyer(), "Refund processed",
                "A refund of " + refundAmount + " was processed for return " + returnId);
        return refund;
    }

    /**
     * Records the decision of not reimbursing an approved return. The
     * rejected refund keeps the order total as the claimed amount for
     * traceability; only PROCESSED refunds count as refunded money.
     */
    public Refund rejectRefund(String approverId, String returnId) {
        Person approver = permissionsService.requirePermission(approverId, BusinessOperation.PROCESS_REFUND);
        Return returnRequest = findReturn(returnId);

        Refund refund = Refund.issueFor(returnRequest, returnRequest.getOrder().getTotalAmount(),
                (Administrator) approver, UUID.randomUUID().toString(), LocalDateTime.now());
        refund.reject();

        returnRepository.save(returnRequest);
        notificationService.notify(returnRequest.getBuyer(), "Refund rejected",
                "The refund of return " + returnId + " was rejected");
        return refund;
    }

    /**
     * @return the refund generated by the given return
     */
    public Refund consultRefund(String requesterId, String returnId) {
        Person requester = permissionsService.requirePermission(requesterId, BusinessOperation.CONSULT_REFUND);
        Return returnRequest = findReturn(returnId);
        ownershipService.requireBuyerAccess(requester, returnRequest.getBuyer());
        if (returnRequest.getRefund() == null) {
            throw new IllegalArgumentException("Return '" + returnId + "' has no refund");
        }
        return returnRequest.getRefund();
    }

    private Return findReturn(String returnId) {
        ServiceValidations.requireText(returnId, "return id");
        return returnRepository.findById(returnId)
                .orElseThrow(() -> new EntityNotFoundException("Return", returnId));
    }
}
