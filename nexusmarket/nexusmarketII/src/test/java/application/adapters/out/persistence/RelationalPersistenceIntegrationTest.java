package application.adapters.out.persistence;

import application.adapters.out.persistence.memory.InMemoryDataStore;
import application.adapters.out.persistence.memory.InMemoryInventoryMovementRepositoryAdapter;
import application.adapters.out.persistence.memory.InMemoryShipmentTrackingRepositoryAdapter;
import application.adapters.out.persistence.mysql.adapters.MysqlOrderRepositoryAdapter;
import application.adapters.out.persistence.mysql.repositories.OrderJpaRepository;
import application.domain.ports.out.InventoryMovementRepository;
import application.domain.ports.out.OrderRepository;
import application.domain.ports.out.ShipmentTrackingRepository;
import com.jayway.jsonpath.JsonPath;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Primary;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.test.annotation.DirtiesContext;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Runs the REST API on the relational persistence adapters (JPA entities,
 * mappers and Spring Data repositories used with MySQL) instead of the
 * in-memory ones. The database is H2 in MySQL mode, so the test needs no
 * external server: it proves that the endpoints really write and read
 * through JPA (schema generated by Hibernate from the entities).
 *
 * MongoDB is not available in this test, so only the two history ports
 * (inventory movements and shipment tracking) are replaced by in-memory
 * adapters.
 */
@SpringBootTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:nexusmarket;MODE=MySQL;DATABASE_TO_LOWER=TRUE;NON_KEYWORDS=VALUE;DB_CLOSE_DELAY=-1",
        "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "spring.jpa.hibernate.ddl-auto=create-drop",
        "spring.mongodb.uri=mongodb://localhost:27017/nexusmarket?serverSelectionTimeoutMS=200&connectTimeoutMS=200"
})
@AutoConfigureMockMvc
@ActiveProfiles("demo")
@DirtiesContext(classMode = DirtiesContext.ClassMode.AFTER_CLASS)
class RelationalPersistenceIntegrationTest {

    @TestConfiguration
    static class HistoryWithoutMongo {

        private final InMemoryDataStore store = new InMemoryDataStore();

        @Bean
        @Primary
        InventoryMovementRepository inMemoryInventoryMovementRepository() {
            return new InMemoryInventoryMovementRepositoryAdapter(store);
        }

        @Bean
        @Primary
        ShipmentTrackingRepository inMemoryShipmentTrackingRepository() {
            return new InMemoryShipmentTrackingRepositoryAdapter(store);
        }
    }

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private OrderRepository orderRepository;

    @Autowired
    private OrderJpaRepository orderJpaRepository;

    @Value("${nexusmarket.demo.password}")
    private String demoPassword;

    @Test
    void purchaseFlowOverHttpIsStoredThroughJpa() throws Exception {
        assertInstanceOf(MysqlOrderRepositoryAdapter.class, orderRepository);

        String buyer = login("buyer@nexusmarket.com");
        mockMvc.perform(get("/api/v1/public/products/product-1").header(HttpHeaders.AUTHORIZATION, "Bearer " + buyer))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.identifier").value("product-1"));
        mockMvc.perform(post("/api/v1/buyer/cart/items").header(HttpHeaders.AUTHORIZATION, "Bearer " + buyer)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"productId\":\"product-1\",\"quantity\":2}"))
                .andExpect(status().isCreated());

        String checkout = mockMvc.perform(post("/api/v1/buyer/orders")
                        .header(HttpHeaders.AUTHORIZATION, "Bearer " + buyer))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.data.orderStatus").value("PENDING_PAYMENT"))
                .andReturn().getResponse().getContentAsString();
        String orderId = JsonPath.read(checkout, "$.data.orderId");

        String admin = login("admin@nexusmarket.com");
        mockMvc.perform(post("/api/v1/admin/orders/" + orderId + "/payment")
                        .header(HttpHeaders.AUTHORIZATION, "Bearer " + admin))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.orderStatus").value("PAID"));

        assertTrue(orderJpaRepository.existsById(orderId));
        assertEquals("PAID", orderRepository.findById(orderId).orElseThrow().getOrderStatus().getCode());

        mockMvc.perform(get("/api/v1/buyer/orders/" + orderId + "/invoice")
                        .header(HttpHeaders.AUTHORIZATION, "Bearer " + buyer))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.totalAmount").value(499800.0));
    }

    private String login(String email) throws Exception {
        String body = mockMvc.perform(post("/api/v1/auth/login").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"" + email + "\",\"password\":\"" + demoPassword + "\"}"))
                .andExpect(status().isOk())
                .andReturn().getResponse().getContentAsString();
        return JsonPath.read(body, "$.data.token");
    }
}
